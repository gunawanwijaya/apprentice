//go:build ignore

package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
)

type contractSpec struct {
	SchemaVersion string `json:"schema_version"`
	Retrieval     struct {
		EmbedDim           int     `json:"embed_dim"`
		RRFK               int     `json:"rrf_k"`
		BM25TopK           int     `json:"bm25_top_k"`
		VectorTopK         int     `json:"vector_top_k"`
		RerankTopK         int     `json:"rerank_top_k"`
		FinalContextChunks int     `json:"final_context_chunks"`
		MinRelevanceScore  float64 `json:"min_relevance_score"`
		BM25K1             float64 `json:"bm25_k1"`
		BM25B              float64 `json:"bm25_b"`
	} `json:"retrieval"`
	Grounding struct {
		RequireCitations    bool `json:"require_citations"`
		AbstainOnLowScore   bool `json:"abstain_on_low_score"`
		EnforceTenantFilter bool `json:"enforce_tenant_filter"`
	} `json:"grounding"`
}

func main() {
	raw, err := os.ReadFile("../../../feature_contract.json")
	if err != nil {
		panic(err)
	}
	var generic any
	if err := json.Unmarshal(raw, &generic); err != nil {
		panic(err)
	}
	canon, err := json.Marshal(generic)
	if err != nil {
		panic(err)
	}
	sum := sha256.Sum256(canon)
	hash := hex.EncodeToString(sum[:])[:12]

	var c contractSpec
	if err := json.Unmarshal(raw, &c); err != nil {
		panic(err)
	}

	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&buf, "package contract")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "const (")
	fmt.Fprintf(&buf, "\tSchemaVersion       = %q\n", c.SchemaVersion)
	fmt.Fprintf(&buf, "\tSchemaHash          = %q\n", hash)
	fmt.Fprintf(&buf, "\tEmbedDim            = %d\n", c.Retrieval.EmbedDim)
	fmt.Fprintf(&buf, "\tRRFK                = %d\n", c.Retrieval.RRFK)
	fmt.Fprintf(&buf, "\tBM25TopK            = %d\n", c.Retrieval.BM25TopK)
	fmt.Fprintf(&buf, "\tVectorTopK          = %d\n", c.Retrieval.VectorTopK)
	fmt.Fprintf(&buf, "\tRerankTopK          = %d\n", c.Retrieval.RerankTopK)
	fmt.Fprintf(&buf, "\tFinalContextChunks  = %d\n", c.Retrieval.FinalContextChunks)
	fmt.Fprintf(&buf, "\tMinRelevanceScore   = %v\n", c.Retrieval.MinRelevanceScore)
	fmt.Fprintf(&buf, "\tBM25K1              = %v\n", c.Retrieval.BM25K1)
	fmt.Fprintf(&buf, "\tBM25B               = %v\n", c.Retrieval.BM25B)
	fmt.Fprintf(&buf, "\tRequireCitations    = %t\n", c.Grounding.RequireCitations)
	fmt.Fprintf(&buf, "\tAbstainOnLowScore   = %t\n", c.Grounding.AbstainOnLowScore)
	fmt.Fprintf(&buf, "\tEnforceTenantFilter = %t\n", c.Grounding.EnforceTenantFilter)
	fmt.Fprintln(&buf, ")")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("contract_gen.go", src, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("Generated contract_gen.go (schema_hash=%s)\n", hash)
}
