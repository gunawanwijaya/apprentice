//go:build ignore

package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
)

type contractSpec struct {
	SchemaVersion string `json:"schema_version"`
	AgentLoop     struct {
		MaxSteps                 int     `json:"max_steps"`
		WallClockTimeoutMS       int     `json:"wall_clock_timeout_ms"`
		MaxRunBudgetUSD          float64 `json:"max_run_budget_usd"`
		MaxConsecutiveToolErrors int     `json:"max_consecutive_tool_errors"`
		BlockDuplicateToolCalls  bool    `json:"block_duplicate_tool_calls"`
		ParallelReadTools        bool    `json:"parallel_read_tools"`
	} `json:"agent_loop"`
	MCPSecurity struct {
		ProtocolVersion                   string `json:"protocol_version"`
		BindPrincipalFromSession          bool   `json:"bind_principal_from_session"`
		LockMutatingToolsOnReadonlyIntent bool   `json:"lock_mutating_tools_on_readonly_intent"`
		MaxAutoRefundIDR                  int64  `json:"max_auto_refund_idr"`
		RequireCitationOnPolicyAnswer     bool   `json:"require_citation_on_policy_answer"`
	} `json:"mcp_security"`
	EvalGate struct {
		RequireReasoningBeforeVerdict bool    `json:"require_reasoning_before_verdict"`
		MinJudgeCohenKappa            float64 `json:"min_judge_cohen_kappa"`
		RequireZeroInjectionEscapes   bool    `json:"require_zero_injection_escapes"`
	} `json:"eval_gate"`
}

func main() {
	raw, err := os.ReadFile("../../../feature_contract.json")
	if err != nil {
		panic(err)
	}
	var generic any
	if err := json.Unmarshal(raw, &generic); err != nil {
		panic(err)
	}
	canon, err := json.Marshal(generic)
	if err != nil {
		panic(err)
	}
	sum := sha256.Sum256(canon)
	hash := hex.EncodeToString(sum[:])[:12]

	var c contractSpec
	if err := json.Unmarshal(raw, &c); err != nil {
		panic(err)
	}

	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&buf, "package contract")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "const (")
	fmt.Fprintf(&buf, "\tSchemaVersion                     = %q\n", c.SchemaVersion)
	fmt.Fprintf(&buf, "\tSchemaHash                        = %q\n", hash)
	fmt.Fprintf(&buf, "\tMaxSteps                          = %d\n", c.AgentLoop.MaxSteps)
	fmt.Fprintf(&buf, "\tWallClockTimeoutMS                = %d\n", c.AgentLoop.WallClockTimeoutMS)
	fmt.Fprintf(&buf, "\tMaxRunBudgetUSD                   = %v\n", c.AgentLoop.MaxRunBudgetUSD)
	fmt.Fprintf(&buf, "\tMaxConsecutiveToolErrors          = %d\n", c.AgentLoop.MaxConsecutiveToolErrors)
	fmt.Fprintf(&buf, "\tBlockDuplicateToolCalls           = %t\n", c.AgentLoop.BlockDuplicateToolCalls)
	fmt.Fprintf(&buf, "\tParallelReadTools                 = %t\n", c.AgentLoop.ParallelReadTools)
	fmt.Fprintf(&buf, "\tMCPProtocolVersion                = %q\n", c.MCPSecurity.ProtocolVersion)
	fmt.Fprintf(&buf, "\tBindPrincipalFromSession          = %t\n", c.MCPSecurity.BindPrincipalFromSession)
	fmt.Fprintf(&buf, "\tLockMutatingToolsOnReadonlyIntent = %t\n", c.MCPSecurity.LockMutatingToolsOnReadonlyIntent)
	fmt.Fprintf(&buf, "\tMaxAutoRefundIDR                  = int64(%d)\n", c.MCPSecurity.MaxAutoRefundIDR)
	fmt.Fprintf(&buf, "\tRequireCitationOnPolicyAnswer     = %t\n", c.MCPSecurity.RequireCitationOnPolicyAnswer)
	fmt.Fprintf(&buf, "\tRequireReasoningBeforeVerdict     = %t\n", c.EvalGate.RequireReasoningBeforeVerdict)
	fmt.Fprintf(&buf, "\tMinJudgeCohenKappa                = %v\n", c.EvalGate.MinJudgeCohenKappa)
	fmt.Fprintf(&buf, "\tRequireZeroInjectionEscapes       = %t\n", c.EvalGate.RequireZeroInjectionEscapes)
	fmt.Fprintln(&buf, ")")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("contract_gen.go", src, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("Generated contract_gen.go (schema_hash=%s)\n", hash)
}
